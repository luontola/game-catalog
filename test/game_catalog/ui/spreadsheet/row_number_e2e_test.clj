(def things-config
  {:collection-key :things
   :id-generator spreadsheet/sequential-id-generator
   :sort-by :thing/name
   :columns [(assoc row-number/column-defaults
               :column/name "#")
             {:column/name "Name"
              :column/entity-key :thing/name}]})

(defn things-page-handler [_request]
  (-> (spreadsheet/table things-config)
      (layout/page)
      (infra.html/response)))

(def test-routes
  [["/"
    {:get {:handler things-page-handler}}]
   (spreadsheet/make-routes things-config)])

(use-fixtures :once (partial browser/fixture test-routes))

(defn wait-for-edit-mode []
  (.waitFor (browser/locator "tr.editing:not(.adding)")))

(defn wait-for-view-mode []
  (.waitFor (browser/locator "tr.editing:not(.adding)")
            (-> (Locator$WaitForOptions.)
                (.setState WaitForSelectorState/HIDDEN))))

(defn wait-for-row-deleted [cell-text]
  (.waitFor (browser/locator (str "text=" cell-text))
            (-> (Locator$WaitForOptions.)
                (.setState WaitForSelectorState/HIDDEN))))

(defn- json-str [^JsonObject obj key]
  (some-> obj (.getAsJsonObject key) (.get "value") (.getAsString)))

(defn visible-table-rows
  "Returns the text of each table row as the user sees it.
  Unlike the DOM, Chrome's accessibility tree includes text generated by CSS,
  such as counters."
  []
  (let [cdp (.newCDPSession (.context browser/*page*) browser/*page*)]
    (try
      (let [nodes (->> (.getAsJsonArray (.send cdp "Accessibility.getFullAXTree") "nodes")
                       (map #(.getAsJsonObject ^JsonElement %)))
            nodes-by-id (into {} (map (juxt #(.getAsString (.get ^JsonObject % "nodeId")) identity)) nodes)
            children (fn [^JsonObject node]
                       (->> (some-> node (.getAsJsonArray "childIds"))
                            (map #(get nodes-by-id (.getAsString ^JsonElement %)))
                            (remove nil?)))
            texts (fn texts [node]
                    (if (= "StaticText" (json-str node "role"))
                      [(json-str node "name")]
                      (mapcat texts (children node))))
            rows (fn rows [node]
                   (if (= "row" (json-str node "role"))
                     [(str/join " " (texts node))]
                     (mapcat rows (children node))))]
        (vec (rows (first nodes))))
      (finally
        (.detach cdp)))))

(defn add-row! [name]
  (let [keyboard (.keyboard browser/*page*)]
    (.click (browser/locator "tr.adding input >> nth=0"))
    (.type keyboard name)
    (.press keyboard "Enter")
    (.waitFor (browser/locator (str "text=" name)))))

(defn delete-row! [name]
  (browser/right-click (browser/locator (str "text=" name)))
  (.click (browser/locator "#context-menu-delete"))
  (wait-for-row-deleted name))

(deftest row-number-test
  (let [keyboard (.keyboard browser/*page*)]
    (db/init-collection! :things [{:entity/id "1" :thing/name "Charlie"}
                                  {:entity/id "2" :thing/name "Alfa"}
                                  {:entity/id "3" :thing/name "Bravo"}])
    (browser/navigate! "/")

    (testing "the backend renders the row numbers of the full page"
      (is (= (html/normalize-whitespace "
              #  Name
              1  Alfa
              2  Bravo
              3  Charlie
                 []")
             (html/visualize-html (browser/locator "table"))))
      (is (= ["# Name" "1 Alfa" "2 Bravo" "3 Charlie" ""]
             (visible-table-rows))))

    (testing "a row in edit mode keeps its row number"
      (.dblclick (browser/locator "text=Bravo"))
      (wait-for-edit-mode)
      (is (= ["# Name" "1 Alfa" "2 Bravo" "3 Charlie" ""]
             (visible-table-rows))))

    (testing "a saved row keeps its row number"
      (.type keyboard "Modified")
      (.press keyboard "Enter")
      (wait-for-view-mode)
      (is (= ["# Name" "1 Alfa" "2 Modified" "3 Charlie" ""]
             (visible-table-rows))))

    (testing "added rows continue the numbering"
      (add-row! "Delta")
      (add-row! "Echo")
      (is (= ["# Name" "1 Alfa" "2 Modified" "3 Charlie" "4 Delta" "5 Echo" ""]
             (visible-table-rows))))

    (testing "deleting a row doesn't change the other row numbers"
      (delete-row! "Modified")
      (is (= ["# Name" "1 Alfa" "3 Charlie" "4 Delta" "5 Echo" ""]
             (visible-table-rows))))

    (testing "reloading the page renumbers the rows"
      (.reload browser/*page*)
      (is (= ["# Name" "1 Alfa" "2 Charlie" "3 Delta" "4 Echo" ""]
             (visible-table-rows))))))
